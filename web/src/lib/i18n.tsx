type I18nContextValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: string) => string;
  tText: (text: string) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function translateText(text: string): string {
  if (typeof window !== "undefined" && window.localStorage.getItem("chatgpt2api.locale") === "zh-CN") {
    return text;
  }
  return legacyPortuguese[text] ?? text;
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("pt-BR");

  useEffect(() => {
    const stored = window.localStorage.getItem("chatgpt2api.locale");
    const nextLocale: Locale = stored === "zh-CN" ? "zh-CN" : "pt-BR";
    setLocaleState(nextLocale);
    document.documentElement.lang = nextLocale;
  }, []);

  const setLocale = (nextLocale: Locale) => {
    setLocaleState(nextLocale);
    window.localStorage.setItem("chatgpt2api.locale", nextLocale);
    document.documentElement.lang = nextLocale;
  };

  const value = useMemo<I18nContextValue>(
    () => ({
      locale,
      setLocale,
      t: (key: string) => messages[locale][key] ?? messages["pt-BR"][key] ?? key,
      tText: translateText,
    }),
    [locale],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error("useI18n must be used inside I18nProvider");
  }
  return context;
}

export function LanguageSwitcher() {
  const { locale, setLocale, t } = useI18n();
  const nextLocale: Locale = locale === "pt-BR" ? "zh-CN" : "pt-BR";
  return (
    <button
      type="button"
      className="rounded-md px-2 py-1 text-[11px] font-medium text-stone-500 transition hover:bg-stone-100 hover:text-stone-900 dark:text-stone-300 dark:hover:bg-white/10 dark:hover:text-white"
      onClick={() => setLocale(nextLocale)}
      title={`${t("language.switch")}: ${t(nextLocale === "pt-BR" ? "language.pt" : "language.zh")}`}
      aria-label={`${t("language.switch")}: ${t(nextLocale === "pt-BR" ? "language.pt" : "language.zh")}`}
    >
      {locale === "pt-BR" ? "PT" : "中文"}
    </button>
  );
}
